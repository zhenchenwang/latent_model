# -----------------------------------------------------------------------------
# Experiment III: Chi-square Test for Categorical Variables
# -----------------------------------------------------------------------------

run_chi_square_tests <- function(iteration) {
  samples <- load_samples(iteration)
  gt_sample <- samples$gt
  syn_sample <- samples$syn

  categorical_vars <- names(gt_sample)[sapply(gt_sample, is.factor)]

  results <- data.frame(variable = character(), p_value = numeric(), stringsAsFactors = FALSE)

  for (var in categorical_vars) {
    test <- chisq.test(gt_sample[[var]], syn_sample[[var]])
    results <- rbind(results, data.frame(variable = var, p_value = test$p.value))
  }

  cat("\n--- Chi-square Test Results for Iteration", iteration, "---\n")
  print(results)
}

