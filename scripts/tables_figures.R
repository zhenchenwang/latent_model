# -----------------------------------------------------------------------------
# Experiment IV: KS Test for Continuous Variables
# -----------------------------------------------------------------------------

run_ks_tests <- function(iteration) {
  samples <- load_samples(iteration)
  gt_sample <- na.omit(samples$gt)
  syn_sample <- na.omit(samples$syn)

  continuous_vars <- c("age", "bmi", "choleratio", "sbp", "sbps")

  results <- data.frame(variable = character(), p_value = numeric(), stringsAsFactors = FALSE)

  for (var in continuous_vars) {
    test <- ks.test(gt_sample[[var]], syn_sample[[var]])
    results <- rbind(results, data.frame(variable = var, p_value = test$p.value))
  }

  cat("\n--- KS Test Results for Iteration", iteration, "---\n")
  print(results)
}

