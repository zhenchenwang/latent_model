# -----------------------------------------------------------------------------
# Experiment VI: Maximum Mean Discrepancy (MMD)
# -----------------------------------------------------------------------------

run_mmd_analysis <- function(iterations, population_data, sample_size = 1000) {
  for (m in iterations) {
    gt_sample <- sample_n(population_data, sample_size)
    gt_sample[is.na(gt_sample)] <- -1

    samples <- load_samples(m)
    syn_sample <- sample_n(samples$syn, sample_size)
    syn_sample[is.na(syn_sample)] <- -1

    output_file <- file.path(results_dir, paste0("mmd_results_iter_", m, ".txt"))

    for (k in 2:4) { # Combinations of 2, 3, and 4 variables
      var_combinations <- combn(names(gt_sample), k, simplify = FALSE)

      for (i in var_combinations) {
        x <- data.matrix(gt_sample[, i, drop = FALSE])
        y <- data.matrix(syn_sample[, i, drop = FALSE])

        mmdo <- kmmd(x, y)

        joint_vars <- paste(i, collapse = ":")
        cat(paste(joint_vars, mmdo@H0, sep = ","), "\n", file = output_file, append = TRUE)
      }
    }
  }
}

