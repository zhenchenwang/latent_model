# Function to load a pair of GT and SYN sample files
load_samples <- function(iteration) {
  gt_path <- file.path(results_dir, paste0(iteration, gt_sample_prefix, ".txt"))
  syn_path <- file.path(results_dir, paste0(iteration, syn_sample_prefix, ".txt"))

  list(
    gt = read.delim(gt_path),
    syn = read.delim(syn_path)
  )
}

# Function to plot density of continuous variables
plot_density_comparison <- function(gt_data, syn_data, var_name) {
  plot(density(na.omit(gt_data[[var_name]])), main = paste("Density Plot for", var_name), xlab = "Value", col = "blue")
  lines(density(na.omit(syn_data[[var_name]])), col = "red")
  legend("topright", legend = c("Ground Truth", "Synthetic"), col = c("blue", "red"), lty = 1)
}

# -----------------------------------------------------------------------------
# Experiment I & II: Distribution Comparison
# -----------------------------------------------------------------------------

run_distribution_comparison <- function(iteration, with_missing = TRUE) {
  samples <- load_samples(iteration)
  gt_sample <- samples$gt
  syn_sample <- samples$syn

  if (!with_missing) {
    gt_sample <- na.omit(gt_sample)
    syn_sample <- na.omit(syn_sample)
  }

  # Balance sample sizes
  min_size <- min(nrow(gt_sample), nrow(syn_sample))
  gt_sample <- sample_n(gt_sample, min_size)
  syn_sample <- sample_n(syn_sample, min_size)

  cat("\n--- Summary for Iteration", iteration, "---\n")
  cat("\nGround Truth Summary:\n")
  print(dfSummary(gt_sample), method = "render")
  cat("\nSynthetic Data Summary:\n")
  print(dfSummary(syn_sample), method = "render")

  # Plot density comparisons for continuous variables
  continuous_vars <- c("age", "bmi", "choleratio")
  for (var in continuous_vars) {
    plot_density_comparison(gt_sample, syn_sample, var)
  }
}

