# -----------------------------------------------------------------------------
# Experiment VII: PRC and ROC Analysis
# -----------------------------------------------------------------------------

run_prc_roc_analysis <- function(iterations, sample_size = 100000, train_ratio = 0.8) {
  results <- list()

  for (m in iterations) {
    samples <- load_samples(m)

    # Prepare GT data
    gt_data <- as.data.frame(lapply(sample_n(samples$gt, sample_size), as.numeric))
    gt_data[is.na(gt_data)] <- -1

    # Prepare SYN data
    syn_data <- as.data.frame(lapply(sample_n(samples$syn, sample_size), as.numeric))
    syn_data[is.na(syn_data)] <- -1

    # Split data
    train_index_gt <- 1:(nrow(gt_data) * train_ratio)
    train_index_syn <- 1:(nrow(syn_data) * train_ratio)

    gt_train_y <- gt_data[train_index_gt, ]$strokeha
    gt_train_x <- subset(gt_data[train_index_gt, ], select = -strokeha)

    syn_train_y <- syn_data[train_index_syn, ]$strokeha
    syn_train_x <- subset(syn_data[train_index_syn, ], select = -strokeha)

    gt_test_y <- gt_data[-train_index_gt, ]$strokeha
    gt_test_x <- subset(gt_data[-train_index_gt, ], select = -strokeha)

    # Train model on synthetic data
    fit <- SuperLearner(
      Y = syn_train_y,
      X = syn_train_x,
      family = "gaussian",
      cvControl = list(V = 10L, stratifyCV = TRUE),
      SL.library = c("SL.bayesglm")
    )

    # Predict on GT test data
    gt_pred <- predict(fit, newdata = gt_test_x)

    # For PRC/ROC, need predictions on synthetic test data as well
    syn_test_y <- syn_data[-train_index_syn, ]$strokeha
    syn_test_x <- subset(syn_data[-train_index_syn, ], select = -strokeha)
    syn_pred <- predict(fit, newdata = syn_test_x)

    # Create evaluation object
    scores <- join_scores(as.numeric(syn_pred$pred), as.numeric(gt_pred$pred))
    labels <- join_labels(syn_test_y, gt_test_y)
    msmdat <- mmdata(scores, labels, modnames = c("SYN", "GT"), dsids = c(1, 2))

    results[[m]] <- msmdat
  }

  # Evaluate and plot
  datapoints <- evalmod(results[[1]]) # Evaluate on the first iteration's results
  plot(datapoints)

  # Granger causality test for PRC and ROC curves
  rocs <- attr(datapoints, "grp_avg")[[1]]
  prcs <- attr(datapoints, "grp_avg")[[2]]

  roc_syn <- rocs[[1]]$y_avg
  roc_gt <- rocs[[2]]$y_avg
  prc_syn <- prcs[[1]]$y_avg
  prc_gt <- prcs[[2]]$y_avg

  roc_granger <- grangertest(roc_gt ~ roc_syn, order = 1)
  prc_granger <- grangertest(prc_gt ~ prc_syn, order = 1)

  cat("\n--- PRC and ROC Analysis Results ---\n")
  print(roc_granger)
  print(prc_granger)

  # AUC values
  aucs <- as.data.frame(attr(datapoints, 'aucs'))
  cat("\nAUC values:\n")
  print(aucs)
}

