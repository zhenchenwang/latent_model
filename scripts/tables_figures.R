# -----------------------------------------------------------------------------
# Experiment V: Kullback-Leibler Divergence (KLD) Comparison
# -----------------------------------------------------------------------------

calculate_kld <- function(gt_values, syn_values) {
  den_gt <- density(na.omit(gt_values))
  den_syn <- density(na.omit(syn_values))
  KLD(den_gt$y, den_syn$y)$sum.KLD.px.py
}

run_kld_analysis <- function(iterations, population_data) {
  kld_results_gt <- list()
  kld_results_syn <- list()
  continuous_vars <- c("age", "bmi", "choleratio", "sbp", "sbps")

  for (i in iterations) {
    samples <- load_samples(i)

    # KLD between synthetic and population
    kld_syn_iter <- sapply(continuous_vars, function(var) {
      calculate_kld(population_data[[var]], samples$syn[[var]])
    })
    kld_results_syn[[i]] <- kld_syn_iter^2

    # KLD between ground truth sample and population
    kld_gt_iter <- sapply(continuous_vars, function(var) {
      calculate_kld(population_data[[var]], samples$gt[[var]])
    })
    kld_results_gt[[i]] <- kld_gt_iter^2
  }

  kld_syn_df <- as.data.frame(do.call(rbind, kld_results_syn))
  kld_gt_df <- as.data.frame(do.call(rbind, kld_results_gt))

  cat("\n--- KLD Analysis Results ---\n")
  cat("\nAverage KLD for Synthetic Data:\n")
  print(colMeans(kld_syn_df))
  cat("\nAverage KLD for Ground Truth Samples:\n")
  print(colMeans(kld_gt_df))

  return(list(syn = kld_syn_df, gt = kld_gt_df))
}

